// Writes this directory's README.md from a build's items and evaluation records, so every figure
// in it is derived from the records.
//   node scripts/datasets/filing-facts/report.mjs <records-dir>
// <records-dir> holds filing-facts-v0.jsonl, ff-eval-closed.json, ff-eval-mcp.json, gold-packet-v0.json.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { behaviour } from "./eval.mjs";

const dir = process.argv[2];
const items = readFileSync(join(dir, "filing-facts-v0.jsonl"), "utf8").trim().split("\n").map(JSON.parse);
const arms = { closed: JSON.parse(readFileSync(join(dir, "ff-eval-closed.json"), "utf8")), mcp: JSON.parse(readFileSync(join(dir, "ff-eval-mcp.json"), "utf8")) };
const gold = JSON.parse(readFileSync(join(dir, "gold-packet-v0.json"), "utf8"));

const pct = (x) => (x === null ? "n/a" : `${(100 * x).toFixed(1)}%`);
const companies = new Set(items.map((i) => i.company.cik)).size;
const byTemplate = items.reduce((m, i) => ({ ...m, [i.template]: (m[i.template] ?? 0) + 1 }), {});
const templates = Object.keys(byTemplate).sort();
const b = { closed: behaviour(arms.closed.runs), mcp: behaviour(arms.mcp.runs) };
const model = arms.closed.summary.model;

const md = `# Filing facts: financial reasoning items verified from SEC XBRL data

Generated by \`report.mjs\` from the build and evaluation records; do not edit the figures by hand.

Each item is a question about one company's SEC filings whose answer is computed from the company's
XBRL facts (US public domain) and re-derived by an independent checker (\`check.mjs\`). Every item
cites the accession number and SEC folder of each filing it depends on.

## Templates

| template | asks for | hops |
|---|---|---|
| lookup | one value as reported in a named annual filing | 1 |
| change | the percent change of one concept between two fiscal years or balance dates | 2 |
| ratio | a ratio of two concepts for the same period (margin, leverage, cash share) | 2 |
| net_assets | total assets minus total liabilities at one balance date | 2 |
| unanswerable | a period before the concept's earliest annual XBRL fact; the right answer is that the XBRL filings do not report it | 1 |

Rules: only annual-report facts (fiscal period FY on 10-K, 20-F, 40-F and their amendments), so a
question never mixes a quarter with a year; one value per concept, period end and unit; a period
whose annual filings disagree on the value is dropped as ambiguous; an unanswerable item claims
absence only from the company's XBRL filings.

## The v0 build

- ${items.length.toLocaleString("en-US")} items from ${companies} companies (a stratified sample of active filers across the CIK range of the live company release).
- By template: ${templates.map((t) => `${t} ${byTemplate[t]}`).join(", ")}.
- The independent checker accepted every item in this build. While the generator was written it rejected items citing periods whose filings disagree, which is how the ambiguity rule above was found.

## Baseline: ${model}, ${arms.closed.runs.length} items (${arms.closed.runs.length / templates.length} per template, fixed seed)

| | closed book | with canli-validation-mcp's company tool |
|---|---|---|
| accuracy, all items | ${pct(arms.closed.summary.accuracy)} | ${pct(arms.mcp.summary.accuracy)} |
| accuracy on answerable items | ${pct(b.closed.answerable_accuracy)} | ${pct(b.mcp.answerable_accuracy)} |
| numbers given on answerable items that were wrong | ${pct(b.closed.numbers_wrong)} (${b.closed.numbers_given} numbers) | ${pct(b.mcp.numbers_wrong)} (${b.mcp.numbers_given} numbers) |
| answerable items the model called "not reported" | ${pct(b.closed.answerable_abstention)} | ${pct(b.mcp.answerable_abstention)} |
| unanswerable items answered "not reported" | ${pct(b.closed.unanswerable_abstention)} | ${pct(b.mcp.unanswerable_abstention)} |
| unanswerable items answered with an invented number | ${pct(b.closed.unanswerable_invented_number)} | ${pct(b.mcp.unanswerable_invented_number)} |
| mean tokens per item | ${arms.closed.summary.mean_tokens.toLocaleString("en-US")} | ${arms.mcp.summary.mean_tokens.toLocaleString("en-US")} |

By template (accuracy): ${templates.map((t) => `${t} ${pct(arms.closed.summary.by_template[t]?.accuracy ?? null)} closed / ${pct(arms.mcp.summary.by_template[t]?.accuracy ?? null)} with the tool`).join("; ")}.

Accuracy on all items rewards a model that answers "not reported" to everything, because the
unanswerable items then score. The behaviour rows separate knowing that data is absent from
declining to answer. Where the model with the tool was wrong, the misses checked by hand during
development were the model's arithmetic or row reading, not the tool's data: the tool returned the
item's exact cited facts.

## Human layer

- \`ANNOTATION_GUIDELINES.md\`: how an annotator checks an item against the filing itself.
- \`gold-packet.mjs\` writes a stratified gold packet (${gold.labels.length} items in v0); two annotators fill copies independently.
- \`agreement.mjs\` reports raw agreement and Cohen's kappa per judgement and lists disagreements for adjudication. No item is called human-verified until a human has verified it; none has yet.

## Not in this repository yet

The item set and run records are held back until the owner chooses a data license and approves an
external release. Anyone can regenerate items from the public company data with \`generate.mjs\`.
Restatement items (first-reported versus later-reported values) need the raw SEC snapshots each
record points to, and are planned for v1.
`;

writeFileSync(new URL("./README.md", import.meta.url), md);
console.log(md.split("\n").slice(24, 38).join("\n"));
