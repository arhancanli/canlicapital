// =============================================================================
// CANLI CAPITAL / scripts/build-company-registered-names.mjs
// -----------------------------------------------------------------------------
// Writes scripts/lib/company-registered-names.mjs from public/api/v1/company-names.json: for each company in the
// active release whose name differs from the SEC's (the index's other_names), the name the SEC registers it
// under. A filing made jointly with a subsidiary or a parent can leave the release with the co-registrant's
// name (CIK 70858, Bank of America, recorded as "BofA Finance LLC"), and a company renamed since its filings
// were captured keeps its old name there. Pages name the company as the SEC does.
//
// Run after build-company-names.mjs at each release; company-label.test.mjs checks the two agree.
//   node scripts/build-company-registered-names.mjs
// =============================================================================
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCE = "public/api/v1/company-names.json";
export const OUTPUT = "scripts/lib/company-registered-names.mjs";

// A name without its case, punctuation, word order, state or country tag and legal form, so only a different name
// counts: "Microsoft Corporation" and "MICROSOFT CORP", "W. R. BERKLEY CORP" and "BERKLEY W R CORP", "AIR PRODUCTS AND
// CHEMICALS, INC." and "Air Products & Chemicals, Inc." are each one name; "BofA Finance LLC" and "BANK OF AMERICA CORP
// /DE/" are two. Apostrophes do not count either: the SEC writes McDONALD'S as MCDONALDS.
const LEGAL = new Set(["inc", "incorporated", "incorporation", "corp", "corporation", "company", "co", "limited", "ltd", "llc", "lp", "plc"]);
const PLACES = new Set(["de", "pa", "tx", "nv", "md", "ny", "ca", "fl", "nj", "mn", "oh", "wa", "ma", "va", "ga", "il", "co", "ut", "cayman", "islands", "singapore", "colorado", "delaware", "nevada"]);
export function nameCore(name) {
  const words = String(name).toLowerCase().replace(/['’]/g, "").replace(/&/g, " and ").replace(/\([^)]*\)/g, " ").replace(/[\\/][^\\/]*[\\/]?$/g, " ")
    .replace(/[^a-z0-9]+/g, " ").trim().split(/\s+/).filter((w) => w && !LEGAL.has(w));
  while (words.length > 1 && PLACES.has(words.at(-1))) words.pop();
  return words.filter((w) => w !== "the").sort().join(" ");
}

/** {ten-digit CIK: the SEC's registered name} for every company whose release name is a different name. */
export function registeredNames(index) {
  if (index?.schema !== "canli.company-names.v1" || !Array.isArray(index.other_names?.rows) || !Array.isArray(index.rows)) throw new Error(`${SOURCE} has no other_names`);
  const released = new Map(index.rows.map(([cik, name]) => [cik, name]));
  const out = {};
  for (const [cik, names] of index.other_names.rows) {
    if (!Number.isSafeInteger(cik) || !Array.isArray(names) || names.length !== 1 || typeof names[0] !== "string" || !names[0].trim()) throw new Error(`${SOURCE}: unexpected other_names row for ${cik}`);
    if (nameCore(names[0]) !== nameCore(released.get(cik) ?? "")) out[String(cik).padStart(10, "0")] = names[0].trim();
  }
  return out;
}

export function renderModule(index) {
  const names = registeredNames(index);
  return `// Generated by scripts/build-company-registered-names.mjs from ${SOURCE} (release ${index.release_hash}).\n` +
    `// The SEC's registered name for each company whose release name differs from it. Do not edit by hand.\n` +
    `export const REGISTERED_NAMES = Object.freeze(${JSON.stringify(names)});\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const index = JSON.parse(readFileSync(resolve(ROOT, SOURCE), "utf8"));
  writeFileSync(resolve(ROOT, OUTPUT), renderModule(index));
  console.log(`${OUTPUT}: ${Object.keys(registeredNames(index)).length} registered names`);
}
