// scripts/build-validation-api.mjs
// Writes the two derived files the validation API needs: the sha256 of every core and contract a
// verdict binds to (so a receipt can name what computed it), and the public limits artifact (so the
// figures on /developers trace to a published source, per audit-published-numbers).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { LIMITS, LIMITS_TEXT } from "../api/_lib/limits.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const BOUND = [
  "js/dsr-core.js", "js/moments-core.js", "js/pbo-core.js", "js/breadth-core.js",
  "js/paper-evidence-core.js", "standards/paper-evidence/schema.json",
  "public/glassbox/deflated_sharpe_calculator_contract.json", "standards/validation-api/vectors.json",
];
const sha = (p) => `sha256:${createHash("sha256").update(readFileSync(resolve(ROOT, p))).digest("hex")}`;
const files = Object.fromEntries(BOUND.map((p) => [p, sha(p)]));
const body = `// GENERATED by scripts/build-validation-api.mjs. Do not edit; run the script.\nexport const BINDINGS = Object.freeze(${JSON.stringify({ generated_from: BOUND, files }, null, 2)});\n`;
writeFileSync(resolve(ROOT, "api/_lib/bindings.generated.js"), body);
mkdirSync(resolve(ROOT, "public/glassbox"), { recursive: true });
const limits = {
  schema: "canli.validation-api-limits.v1",
  source: "api/_lib/limits.js",
  limits: LIMITS,
  limits_text: LIMITS_TEXT,
  claim_boundary: "Service quotas and the standing caveats attached to every verdict. They describe the service, not any strategy.",
};
writeFileSync(resolve(ROOT, "public/glassbox/validation_api_limits.json"), `${JSON.stringify(limits, null, 2)}\n`);
console.log(`validation-api: ${BOUND.length} bindings, limits artifact written`);
