// Writes README.md for this experiment from plain.json and mcp.json, so every figure in it is
// derived from the run records.   node mcp/bench/agent/experiments/2026-09-26-plain-control/summarize.mjs
import { readFileSync, writeFileSync } from "node:fs";

const read = (f) => JSON.parse(readFileSync(new URL(f, import.meta.url), "utf8"));
const arms = { plain: read("./plain.json"), mcp: read("./mcp.json") };
const kind = (t) => (t.startsWith("co-") ? "company data" : t.startsWith("lim-") ? "limits questions" : "validation arithmetic");

export function stats(runs) {
  const tokens = runs.reduce((a, r) => a + r.prompt_tokens + r.completion_tokens, 0);
  const prompt = runs.reduce((a, r) => a + r.prompt_tokens, 0);
  const cached = runs.reduce((a, r) => a + r.cached_tokens, 0);
  const correct = runs.filter((r) => r.correct).length;
  return { runs: runs.length, correct, accuracy: correct / runs.length, tokens, perRun: tokens / runs.length, perCorrect: correct ? tokens / correct : Infinity, cachedShare: prompt ? cached / prompt : 0, errors: runs.filter((r) => r.error).length };
}

const pct = (x) => `${(100 * x).toFixed(1)}%`;
const int = (x) => (Number.isFinite(x) ? Math.round(x).toLocaleString("en-US") : "none correct");
const saving = (a, b) => pct(1 - b / a);

const all = { plain: stats(arms.plain.runs), mcp: stats(arms.mcp.runs) };
const kinds = ["validation arithmetic", "company data", "limits questions"];
const byKind = Object.fromEntries(kinds.map((k) => [k, { plain: stats(arms.plain.runs.filter((r) => kind(r.task) === k)), mcp: stats(arms.mcp.runs.filter((r) => kind(r.task) === k)) }]));
const errors = arms.plain.runs.filter((r) => r.error).map((r) => `\`${r.task}\`: ${r.error.replace(/ in organization \S+/, "").slice(0, 110)}`);
const companyFetches = arms.plain.runs.filter((r) => r.task.startsWith("co-")).flatMap((r) => r.tool_calls ?? []).filter((c) => c.startsWith("http_get"));
const wholeFile = companyFetches.filter((c) => c.includes("/companyfacts/")).length;

const row = (label, s) => `| ${label} | ${s.runs} | ${pct(s.accuracy)} | ${int(s.tokens)} | ${int(s.perRun)} | ${int(s.perCorrect)} | ${pct(s.cachedShare)} |`;
const head = "| arm | runs | accuracy | total tokens | tokens per task | tokens per correct answer | prompt tokens from cache |\n|---|---|---|---|---|---|---|";

const md = `# The saving against a plain agent (2026-09-26)

Generated by \`summarize.mjs\` from \`plain.json\` and \`mcp.json\`; do not edit the figures by hand.

The same 24 benchmark tasks, three passes each, ${arms.mcp.model}, run one arm after the other:

- **mcp**: this server (${arms.mcp.server.version}), local mode, company data read from canlicapital.com.
- **plain** (the control, \`--arm plain\`): no Canli Capital tools. A web fetch that reaches any public https URL except canlicapital.com, sending the User-Agent SEC EDGAR's API asks for, and a calculator that includes the normal CDF and its inverse. It is what an agent without this server works with. Its tool results are cut at ${arms.plain.tool_text_cap_chars.toLocaleString("en-US")} characters, a size a model's context holds, so truncation does not make the control cheaper than it would be.

Rate-limit refusals (HTTP 429) were waited out and retried in both arms, so the plain arm's times include those waits; compare tokens and accuracy, not time.

## Result

${head}
${row("plain", all.plain)}
${row("mcp", all.mcp)}

Per correct answer, the server used **${saving(all.plain.perCorrect, all.mcp.perCorrect)} fewer tokens** than the plain agent. In total tokens for the same tasks it used ${saving(all.plain.tokens, all.mcp.tokens)} fewer, while answering ${pct(all.mcp.accuracy)} correctly against ${pct(all.plain.accuracy)}.

## By kind of task

${kinds.map((k) => `### ${k}\n\n${head}\n${row("plain", byKind[k].plain)}\n${row("mcp", byKind[k].mcp)}`).join("\n\n")}

- **Company data** is where the saving is largest: per correct answer ${saving(byKind["company data"].plain.perCorrect, byKind["company data"].mcp.perCorrect)} fewer tokens. ${wholeFile} of the plain arm's ${companyFetches.length} fetches for these tasks downloaded a company's whole EDGAR file (Apple's is 3.8 MB), which the model then read again on the next turn.
- **Validation arithmetic** costs the plain agent fewer tokens per attempt, because it has no tool list to read, but it answered ${pct(byKind["validation arithmetic"].plain.accuracy)} correctly; per correct answer the server used ${saving(byKind["validation arithmetic"].plain.perCorrect, byKind["validation arithmetic"].mcp.perCorrect)} fewer.
- **Limits questions** need no tool; the plain agent answers them with fewer tokens.

## Failures in the plain arm, counted as wrong

${errors.map((e) => `- ${e}`).join("\n")}

Without the two prompts the provider refused as a policy false positive, the plain arm's accuracy would be ${pct(all.plain.correct / (all.plain.runs - errors.filter((e) => e.includes("flagged")).length))}. The request that was too large is the plain approach failing on its own: one company file did not fit the provider's per-minute token allowance.

## Scope

One model, our tasks, one day. It measures this server against a capable agent without it, not against other servers. The records are the full per-run results, including every URL the plain agent fetched.
`;

writeFileSync(new URL("./README.md", import.meta.url), md);
console.log(md.split("\n").slice(0, 16).join("\n"));
